// Геометрия барабана. Все вычисления скролла завязаны на эти константы:
// scrollTop выбранного элемента === index * ITEM_HEIGHT (см. getIndexByScrollTop).
export const ITEM_HEIGHT = 34;

// Нечётное число, чтобы выбранный элемент оказался ровно по центру колонки.
export const VISIBLE_ITEMS = 5;

export const WHEEL_HEIGHT = ITEM_HEIGHT * VISIBLE_ITEMS;

// Сколько пустого места нужно сверху и снизу, чтобы крайние элементы вставали в центр.
export const EDGE_PADDING = ITEM_HEIGHT * ((VISIBLE_ITEMS - 1) / 2);

// Пауза без событий скролла, после которой считаем, что барабан остановился.
export const SETTLE_MS = 140;

// --- Инерция ---
// Барабан крутится сам после броска. Нативный fling есть только у тач-скролла, поэтому
// перетаскивание ведём сами: так «толчок» работает и пальцем, и мышью, и одинаково
// ощущается на всех платформах.

// Доля скорости, сохраняемая за кадр при 60fps. Меньше — барабан встаёт резче.
export const FRICTION_PER_FRAME = 0.94;

export const FRAME_MS = 1000 / 60;

// Скорость в px/ms, ниже которой барабан считаем остановившимся.
export const MIN_VELOCITY = 0.02;

// Потолок броска: без него резкий свайп улетал бы на сотни строк.
export const MAX_VELOCITY = 4;

// Сдвиг в px, после которого жест перестаёт быть кликом по строке.
export const DRAG_THRESHOLD = 4;

// Если перед отпусканием палец простоял дольше — это не бросок, а точная доводка.
export const STALE_DRAG_MS = 80;
